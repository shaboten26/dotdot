interface RectRun {
  x: number
  y: number
  w: number
}

const compiledRectsCache = new Map<PixelIconName, RectRun[]>()

function getCompiledIconRects(name: PixelIconName): RectRun[] {
  const cached = compiledRectsCache.get(name)
  if (cached) return cached

  const rows = ICON_BITMAPS_16[name]
  const runs: RectRun[] = []
  for (let y = 0; y < rows.length; y++) {
    const row = rows[y]
    let x = 0
    while (x < row.length) {
      if (row[x] === '#') {
        let end = x + 1
        while (end < row.length && row[end] === '#') {
          end++
        }
        runs.push({ x, y, w: end - x })
        x = end
      } else {
        x++
      }
    }
  }
  compiledRectsCache.set(name, runs)
  return runs
}

export interface PixelIconProps {
  name: PixelIconName
  /** Icon size in px (defaults to CSS variable --tool-icon-size or 18px) */
  size?: number | string
  className?: string
  style?: React.CSSProperties
}

export function PixelIcon({ name, size, className = '', style }: PixelIconProps) {
  const runs = useMemo(() => getCompiledIconRects(name), [name])
  const dim = size ?? 'var(--tool-icon-size, 20px)'

  return (
    <span
      aria-hidden="true"
      style={{
        width: dim,
        height: dim,
        minWidth: dim,
        minHeight: dim,
        flexShrink: 0,
        aspectRatio: '1 / 1',
        ...style,
      }}
      className={`inline-flex items-center justify-center select-none ${className}`}
    >
      <svg
        viewBox="0 0 16 16"
        preserveAspectRatio="xMidYMid meet"
        shapeRendering="crispEdges"
        fill="currentColor"
        className="w-full h-full block"
      >
        {runs.map((r, i) => (
          <rect key={i} x={r.x} y={r.y} width={r.w} height={1} />
        ))}
      </svg>
    </span>
  )
}

